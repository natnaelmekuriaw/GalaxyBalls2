export const SNAKE_TRANSLATIONS: Record<Language, SnakeTranslations> = { en, am, om };

export function translateSnake(
  language: Language,
  key: SnakeTranslationKey,
  values: Record<string, string | number> = {},
): string {
  const message = SNAKE_TRANSLATIONS[language]?.[key] ?? en[key];
  return message.replace(/\{(\w+)\}/g, (token, name: string) =>
    values[name] === undefined ? token : String(values[name]),
  );
}
